export function sampleRowsFor(userId: string): Prisma.PropertyCreateManyInput[] {
  const now = Date.now();
  return SAMPLE_PROPERTIES.map(({ daysAgo, ...p }) => {
    const ts = new Date(now - daysAgo * 86_400_000);
    return { ...p, userId, isSample: true, createdAt: ts, updatedAt: ts };
  });
}
